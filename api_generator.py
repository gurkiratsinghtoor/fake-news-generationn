"""
API based synthetic news generator (Google Gemini API - has a free tier).

Creates FICTIONAL, labelled news-style articles (invented people/places/organisations)
to stress-test the predictor. Fake-style samples imitate sensational / clickbait writing
patterns only; they never use real people, real events, health or election claims.

Setup:   export GEMINI_API_KEY="your-key"         (free key at https://aistudio.google.com/apikey)
Usage:   python src/api_generator.py --n 20        -> saves data/synthetic_api.csv and tests the model
"""
import argparse
import json
import os
import re
import time
import pandas as pd

from generator import generate as template_generate

MODEL = os.getenv("GEMINI_MODEL", "gemini-3.8-flash")
# Backup models tried in order if the main one is overloaded (503) or rate limited (429)
FALLBACK_MODELS = ["gemini-3.7-flash", "gemini-3.5-flash", "gemini-3.5-flash-lite"]


def get_key(api_key=None):
    """Key passed in (e.g. from the app) or from environment variables."""
    return api_key or os.getenv("GEMINI_API_KEY") or os.getenv("GOOGLE_API_KEY")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SYSTEM = (
    "You create synthetic, clearly fictional news-style text for testing a fake news classifier. "
    "Rules: use ONLY invented people, places and organisations; never mention real people, real "
    "organisations, real events, elections, or medical/health claims; no hateful or violent content. "
    "Output valid JSON only, no markdown fences."
)

STYLE = {
    1: ("FAKE-STYLE: sensational, clickbait, emotional, ALL-CAPS words, exclamation marks, vague "
        "anonymous sources, conspiracy tone, urging readers to share."),
    0: ("REAL-STYLE: neutral, factual journalism tone, named official sources, dates, balanced "
        "wording, no sensationalism."),
}


def _parse(raw: str) -> list:
    """Extract the JSON list from the model reply (tolerates stray text/fences)."""
    raw = re.sub(r"```(?:json)?", "", raw).strip()
    start, end = raw.find("["), raw.rfind("]")
    return json.loads(raw[start:end + 1])


def _call_with_retry(client, types, prompt, retries=3):
    """Call Gemini; retry on 503/429 with waiting, then try backup models."""
    last_err = None
    for model in [MODEL] + [m for m in FALLBACK_MODELS if m != MODEL]:
        for attempt in range(retries):
            try:
                return client.models.generate_content(
                    model=model,
                    contents=prompt,
                    config=types.GenerateContentConfig(
                        system_instruction=SYSTEM,
                        response_mime_type="application/json",
                        max_output_tokens=16000,
                        temperature=1.0,
                    ),
                )
            except Exception as e:
                last_err = e
                msg = str(e)
                busy = any(c in msg for c in ("503", "429", "UNAVAILABLE", "RESOURCE_EXHAUSTED"))
                notfound = "404" in msg or "NOT_FOUND" in msg
                if notfound:
                    break                      # model not available -> try next model
                if not busy:
                    raise                      # auth/other errors: stop and show them
                time.sleep(2 * (attempt + 1))  # wait 2s, 4s, 6s then retry
    raise last_err


def generate_with_api(n_per_class: int = 5, topic_hint: str = "local government and city services", api_key=None) -> pd.DataFrame:
    """Return DataFrame(title, text, label[1=fake,0=real]) generated by the API."""
    from google import genai
    from google.genai import types
    client = genai.Client(api_key=get_key(api_key))
    rows = []
    for label in (1, 0):
        prompt = (
            f"Write {n_per_class} different fictional news articles about {topic_hint}.\n"
            f"Style: {STYLE[label]}\n"
            "Each article: a headline and a body of 60-90 words.\n"
            'Return a JSON list like [{"title": "...", "text": "..."}].'
        )
        resp = _call_with_retry(client, types, prompt)
        raw = resp.text or ""
        for item in _parse(raw):
            rows.append({"title": item["title"], "text": item["text"], "label": label})
    return pd.DataFrame(rows).sample(frac=1, random_state=1).reset_index(drop=True)


def generate_samples(n_per_class: int = 5, topic_hint: str = "local government and city services", api_key=None):
    """Gemini API if a key is available, else template fallback.
    Returns (DataFrame, source_name, error_message_or_None)."""
    key = get_key(api_key)
    if not key:
        return template_generate(n_per_class * 2), "template fallback", "No API key found (set GEMINI_API_KEY or paste it in the app)."
    try:
        return generate_with_api(n_per_class, topic_hint, key), "Gemini API", None
    except Exception as e:  # network/auth/quota/parse errors -> fall back gracefully
        return template_generate(n_per_class * 2), "template fallback", f"{type(e).__name__}: {e}"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=10, help="samples per class")
    ap.add_argument("--topic", default="local government and city services")
    a = ap.parse_args()

    df, source, err = generate_samples(a.n, a.topic)
    if err:
        print("WARNING:", err)
    out = os.path.join(ROOT, "data", "synthetic_api.csv")
    df.to_csv(out, index=False)
    print(f"Generated {len(df)} samples via {source} -> {out}")

    from predict import load, predict
    bundle = load()
    df["pred"] = [1 if predict(t + " " + b, bundle)["label"] == "FAKE" else 0 for t, b in zip(df.title, df.text)]
    acc = (df.pred == df.label).mean()
    print(f"Model accuracy on these generated samples: {acc:.1%}")
    print(df[df.pred != df.label][["title", "label", "pred"]].to_string(index=False) or "No mistakes")
